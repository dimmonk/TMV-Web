// @ts-check
import { defineConfig } from 'astro/config';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { moveSlotMarkers } from './src/lib/sq-slot-marker.js';

/** Built pages carry each Square link's slot in `data-sq` (see `src/lib/sq-slot-marker.js`). */
const squareSlotMarkers = {
  name: 'tmv-square-slot-markers',
  hooks: {
    'astro:build:done': ({ dir }) => {
      const walk = (d) => readdirSync(d, { withFileTypes: true }).forEach((e) => {
        const f = join(d, e.name);
        if (e.isDirectory()) { walk(f); return; }
        if (!e.name.endsWith('.html')) return;
        const html = readFileSync(f, 'utf8');
        const out = moveSlotMarkers(html);
        if (out !== html) writeFileSync(f, out);
      });
      walk(fileURLToPath(dir));
    },
  },
};

/**
 * The browser floor is Safari 13.1 / iOS 13.4 (TMV-Members runs on the same floor). Astro builds the client
 * for 'esnext', and the minifier then writes logical assignment (`a ||= b`), which Safari 14 added: a module
 * holding one does not parse on the floor, so none of its code runs. Target the floor for the CLIENT bundle
 * so the bundler lowers such syntax in every script it emits (ours, and Astro's router and prefetch alike).
 * `?.` and `??` are already Safari 13.1 and stay as written. The server build keeps its own target (its
 * top-level await needs it), and CSS stays as authored ('esnext', as Astro builds it), so this changes
 * the client scripts only. `tests/site-config-render.test.mjs` fails if a built script needs lowering.
 */
const browserFloor = {
  name: 'tmv-browser-floor',
  configEnvironment(name) {
    if (name !== 'client') return undefined;
    return { build: { target: ['safari13.1', 'ios13.4'], cssTarget: 'esnext' } };
  },
};

// Production host: Firebase Hosting (site `themonkeyvault` in project
// tmv-management), deployed by the TMV-Members repo's `hosting:web` target
// (scripts/build-web.sh assembles this dist/ + the /account and /waiver
// surfaces). Staging URL: https://themonkeyvault.web.app; the custom domain
// themonkeyvault.com attaches at DNS cutover — `site` already points there so
// canonicals/OG/sitemap are correct from day one (and staging pages canonical
// to the real domain instead of getting indexed).
//
// No `base`: the site serves from the domain root. (The old GitHub Pages
// deploy needed base '/TMV-Web'; Pages is retired — clean break.)
// Sitemap is generated by src/pages/sitemap.xml.ts (no external integration).
export default defineConfig({
  integrations: [squareSlotMarkers],
  site: 'https://themonkeyvault.com',
  // Trailing slashes everywhere, matching directory hosting. Firebase serves
  // `/route/` as 200 and 301-redirects `/route` to it; emitting the slashed
  // form (see url() in src/data/site.ts) keeps every internal link redirect-free
  // so Astro's client router does a clean swap instead of falling back to a full
  // page load. 'always' makes Astro's own canonical + sitemap URLs match.
  trailingSlash: 'always',
  build: { format: 'directory' },
  // `assetsInlineLimit: 0`: Astro would otherwise inline every script under 4 KB
  // into the page as an inline <script type="module">. The hosting
  // Content-Security-Policy (TMV-Members firebase.json, hosting:web) allows no
  // inline script, and a per-release hash list would drift; so every script is a
  // file under /_astro/ ('self'). The render test fails if a built page carries
  // an inline executable script or an inline event handler.
  vite: { plugins: [browserFloor], build: { assetsInlineLimit: 0 } },
  // Dev-only overlay (never ships in `astro build`/production) — off because
  // it sits over the phone-width preview during mobile work.
  devToolbar: { enabled: false },
  // Every internal link is prefetched as soon as it scrolls into view, so by
  // the time it's tapped the target HTML is already cached and the swap is
  // instant. The previous 'hover' default never fired on touch devices — a tap
  // then had to fetch the page on click, which is the delay between clicking a
  // link and the page appearing. 'viewport' is the right default for a small
  // static site: pages are tiny HTML on a CDN, and it makes taps feel instant.
  prefetch: { prefetchAll: true, defaultStrategy: 'viewport' },
});
